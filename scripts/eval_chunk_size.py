"""Chunk-size tuning eval: 500/75 vs 800/120 vs 1200/150.

Indexes the corpus in data/ at three (CHUNK_SIZE, CHUNK_OVERLAP) configs,
each into its own ISOLATED temp Chroma directory/collection (never touching
the real chroma_store/), retrieves TOP_K per known-answer question against
each config, and prints a hit table showing which configs returned a chunk
from the expected (source, page).

The three questions are written against facts in the two dense documents
generated by ``scripts/generate_dense_docs.py``
(data_security_policy_handbook.pdf, widgetx_technical_operations_manual.pdf).
Two of the three sit at the tail of a long, single-topic page (~500-650
tokens) so that CHUNK_SIZE=500 actually splits the page into multiple
chunks -- separating the answer from its section heading -- while 800/1200
keep the whole page as one chunk. The third is a short, clean control fact
that should be retrievable at every chunk size.

Usage (real OpenAI embeddings -- costs a small number of embedding tokens,
see module docstring in backend/vectorstore.py):
    .venv/bin/python -m scripts.eval_chunk_size

Usage (no API key -- verify plumbing only, with a deterministic fake
embedder; NOT a substitute for the real eval, results are meaningless
beyond proving the mechanics work):
    .venv/bin/python -m scripts.eval_chunk_size --fake-embeddings
"""

from __future__ import annotations

import argparse
import hashlib
import shutil
import tempfile
from dataclasses import dataclass
from pathlib import Path

from backend.config import PROJECT_ROOT, TOP_K
from backend.ingestion import load_and_chunk_directory
from backend.vectorstore import get_client, ingest_documents, query_collection

CONFIGS = [
    (500, 75),
    (800, 120),
    (1200, 150),
]

FAKE_EMBED_DIM = 32


@dataclass(frozen=True)
class EvalQuestion:
    text: str
    expected_source: str
    expected_page: int
    note: str


QUESTIONS: list[EvalQuestion] = [
    EvalQuestion(
        text=(
            "How many days are backup archives retained in cold storage "
            "before they are automatically purged?"
        ),
        expected_source="data_security_policy_handbook.pdf",
        expected_page=3,
        note="boundary case: '90 days' sits at the tail of a 627-token "
        "page-3 section; splits into 3 chunks at 500/75, stays whole at "
        "800/120 and 1200/150.",
    ),
    EvalQuestion(
        text=(
            "How quickly must a security incident be reported to the "
            "Security Operations Center?"
        ),
        expected_source="data_security_policy_handbook.pdf",
        expected_page=5,
        note="control: short, clean 155-token page -- one chunk at every "
        "configured size.",
    ),
    EvalQuestion(
        text=(
            "What is the recommended calibration interval, in operating "
            "hours, for the WidgetX pressure sensor?"
        ),
        expected_source="widgetx_technical_operations_manual.pdf",
        expected_page=3,
        note="boundary case: '500 operating hours' sits at the tail of a "
        "534-token page-3 section; splits into 2 chunks at 500/75 "
        "(heading isolated), stays whole at 800/120 and 1200/150.",
    ),
]


def _fake_embed_fn(texts: list[str]) -> list[list[float]]:
    """Deterministic, dependency-free embedding for plumbing verification.

    NOT semantically meaningful -- it hashes token-overlap-insensitive
    character n-grams into a fixed-size vector purely so the same text
    always maps to the same vector and different text usually maps to a
    different one. Used only when --fake-embeddings is passed (no API key
    available); never used in production ingest.
    """
    vectors: list[list[float]] = []
    for text in texts:
        vec = [0.0] * FAKE_EMBED_DIM
        words = text.lower().split()
        for word in words:
            digest = hashlib.sha256(word.encode("utf-8")).digest()
            bucket = digest[0] % FAKE_EMBED_DIM
            vec[bucket] += 1.0
        norm = sum(v * v for v in vec) ** 0.5 or 1.0
        vectors.append([v / norm for v in vec])
    return vectors


def _build_config_collection(
    data_dir: Path, chunk_size: int, chunk_overlap: int, tmp_root: Path, embed_fn
):
    """Chunk the corpus at (chunk_size, chunk_overlap) into an isolated collection.

    Uses ``load_and_chunk_directory``'s explicit overrides (not global
    config mutation), so this never touches the real CHROMA_DIR and is safe
    to call repeatedly / concurrently.
    """
    all_chunks = load_and_chunk_directory(
        data_dir, chunk_size=chunk_size, chunk_overlap=chunk_overlap
    )

    persist_dir = tmp_root / f"chroma_{chunk_size}_{chunk_overlap}"
    collection_name = f"eval_{chunk_size}_{chunk_overlap}"
    ingest_documents(
        all_chunks,
        collection_name=collection_name,
        persist_directory=persist_dir,
        reset=True,
        embed_fn=embed_fn,
    )
    return persist_dir, collection_name, len(all_chunks)


def run_eval(use_fake_embeddings: bool = False) -> None:
    data_dir = PROJECT_ROOT / "data"
    embed_fn = _fake_embed_fn if use_fake_embeddings else None

    tmp_root = Path(tempfile.mkdtemp(prefix="smartdoc_chunk_eval_"))
    print(f"Isolated eval indices written under: {tmp_root}")
    if use_fake_embeddings:
        print(
            "WARNING: --fake-embeddings uses a non-semantic hash embedder. "
            "This only proves the eval mechanics work end to end; it does "
            "NOT produce a meaningful chunk-size recommendation.\n"
        )

    results: dict[tuple[int, int], dict[str, bool]] = {}
    chunk_counts: dict[tuple[int, int], int] = {}

    try:
        for chunk_size, chunk_overlap in CONFIGS:
            persist_dir, collection_name, n_chunks = _build_config_collection(
                data_dir, chunk_size, chunk_overlap, tmp_root, embed_fn
            )
            chunk_counts[(chunk_size, chunk_overlap)] = n_chunks
            client = get_client(persist_dir)
            collection = client.get_collection(collection_name)

            hits_per_question: dict[str, bool] = {}
            for q in QUESTIONS:
                hits = query_collection(
                    q.text,
                    collection=collection,
                    top_k=TOP_K,
                    embed_fn=embed_fn,
                )
                found = any(
                    h["metadata"]["source"] == q.expected_source
                    and h["metadata"]["page"] == q.expected_page
                    for h in hits
                )
                hits_per_question[q.text] = found
            results[(chunk_size, chunk_overlap)] = hits_per_question

        _print_report(chunk_counts, results)
    finally:
        shutil.rmtree(tmp_root, ignore_errors=True)
        print(f"\nCleaned up temp eval directory: {tmp_root}")


def _print_report(
    chunk_counts: dict[tuple[int, int], int],
    results: dict[tuple[int, int], dict[str, bool]],
) -> None:
    print("\n=== Chunk-size eval report ===\n")
    print(f"TOP_K = {TOP_K}\n")

    print("Chunk counts per config:")
    for (size, overlap), count in chunk_counts.items():
        print(f"  {size}/{overlap}: {count} chunks")
    print()

    header = f"{'Question':<70} " + " ".join(
        f"{size}/{overlap:<3}" for size, overlap in CONFIGS
    )
    print(header)
    print("-" * len(header))

    config_score = {cfg: 0 for cfg in CONFIGS}
    for q in QUESTIONS:
        row = f"{q.text[:68]:<70} "
        for cfg in CONFIGS:
            hit = results[cfg][q.text]
            row += f"{'HIT ':<8}" if hit else f"{'miss':<8}"
            if hit:
                config_score[cfg] += 1
        print(row)
        print(f"    note: {q.note}")
        print(f"    expected: {q.expected_source} p.{q.expected_page}")

    print("\nScore (questions with a correct source/page in top-k):")
    for cfg in CONFIGS:
        print(f"  {cfg[0]}/{cfg[1]}: {config_score[cfg]}/{len(QUESTIONS)}")

    best_score = max(config_score.values())
    winners = [cfg for cfg, score in config_score.items() if score == best_score]
    print()
    if len(winners) == 1:
        size, overlap = winners[0]
        print(
            f"Recommended default: CHUNK_SIZE={size}, CHUNK_OVERLAP={overlap} "
            f"-- the only config that scored {best_score}/{len(QUESTIONS)}."
        )
    elif len(set(config_score.values())) == 1:
        print(
            "All three configs scored identically. Given the corpus and "
            "questions used here, this eval CANNOT discriminate between "
            "chunk sizes -- do not treat any config as a proven winner "
            "from this run alone."
        )
    else:
        print(
            f"Tied at {best_score}/{len(QUESTIONS)}: {winners}. Falling back "
            "to the mid-size config (800/120) as the safer general default "
            "for prose documents, per DECISIONS.md."
        )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--fake-embeddings",
        action="store_true",
        help="Use a deterministic hash embedder instead of OpenAI (plumbing "
        "verification only, no API key required, not semantically meaningful).",
    )
    args = parser.parse_args()
    run_eval(use_fake_embeddings=args.fake_embeddings)


if __name__ == "__main__":
    main()
